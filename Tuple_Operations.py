# Creating two tuples
tuple1 = (10, 20, 30)
tuple2 = (40, 50, 60)

# Tuple Concatenation
result = tuple1 + tuple2
print("Concatenation:", result)

# Tuple Slicing
print("Slicing:", result[1:4])

# Tuple Unpacking
a, b, c = tuple1

print("Tuple Unpacking:")
print("a =", a)
print("b =", b)
print("c =", c)